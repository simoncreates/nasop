impl TryFrom<capstone::RegId> for X86Register {
    type Error = String;

    fn try_from(rid: capstone::RegId) -> Result<Self, Self::Error> {
        let cs = Capstone::new()
            .x86()
            .mode(arch::x86::ArchMode::Mode64)
            .detail(true)
            .build()
            .map_err(|e| format!("Failed to build Capstone: {}", e))?;
        let capstone_name = cs.reg_name(rid).unwrap_or("invalid".into());
        capstone_name
            .parse()
            .map_err(|_| "Failed to parse RegisterX86".to_string())
    }
}

impl TryFrom<unicorn_engine::RegisterX86> for X86Register {
    type Error = String;

    fn try_from(ureg: unicorn_engine::RegisterX86) -> Result<Self, Self::Error> {
        let reg_str = format!("{:?}", ureg);
        reg_str
            .parse()
            .map_err(|_| "Failed to parse RegisterX86".to_string())
    }
}

