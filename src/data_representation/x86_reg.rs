impl X86Register {
    pub fn size_bits(self) -> u8 {
        match self {
            X86Register::AL | X86Register::CL | X86Register::DL | X86Register::BL => 8,
            X86Register::AX | X86Register::CX | X86Register::DX | X86Register::BX => 16,
            X86Register::EAX
            | X86Register::ECX
            | X86Register::EDX
            | X86Register::EBX
            | X86Register::ESP
            | X86Register::EBP
            | X86Register::ESI
            | X86Register::EDI => 32,
            X86Register::RAX
            | X86Register::RCX
            | X86Register::RDX
            | X86Register::RBX
            | X86Register::RSP
            | X86Register::RBP
            | X86Register::RSI
            | X86Register::RDI
            | X86Register::R8
            | X86Register::R9
            | X86Register::R10
            | X86Register::R11
            | X86Register::R12
            | X86Register::R13
            | X86Register::R14
            | X86Register::R15 => 64,
            _ => 0,
        }
    }
}
