pub fn reg_size(reg: RegisterX86) -> usize {
    use RegisterX86::*;
    match reg {
        // 64-bit
        RAX | RBX | RCX | RDX | RSI | RDI | RBP | RSP | R8 | R9 | R10 | R11 | R12 | R13 | R14
        | R15 | RIP | RFLAGS => 8,

        // 32-bit
        EAX | EBX | ECX | EDX | ESI | EDI | EBP | ESP | R8D | R9D | R10D | R11D | R12D | R13D
        | R14D | R15D => 4,

        // 16-bit
        AX | BX | CX | DX | SI | DI | BP | SP | R8W | R9W | R10W | R11W | R12W | R13W | R14W
        | R15W => 2,

        // 8-bit
        AL | AH | BL | BH | CL | CH | DL | DH | SIL | DIL | BPL | SPL | R8B | R9B | R10B | R11B
        | R12B | R13B | R14B | R15B => 1,

        _ => 8,
    }
}
